@Composable
internal fun appText(text: String): String = appText(text, LocalAppLanguage.current)

internal fun appText(text: String, language: AppLanguage): String {
    val entry = translations[text] ?: return text
    return when (language) {
        AppLanguage.English -> entry.english ?: text
        AppLanguage.Ukrainian -> entry.ukrainian
        AppLanguage.Russian -> entry.russian
    }
}

@Composable
internal fun settingsTabLabel(tab: SettingsTab) = appText(tab.name)
